"""Generate an IDA IDC script that imports the recovered public symbols."""

import argparse
import csv
from collections import defaultdict
from pathlib import Path


def idc_string(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )
    return '"' + escaped + '"'


def generate_idc(symbols: list[dict[str, str]]) -> str:
    grouped: dict[int, list[dict[str, str]]] = defaultdict(list)
    seen_names: dict[str, int] = {}

    for symbol in symbols:
        name = symbol["name"]
        segment = int(symbol["segment"], 0)
        offset = int(symbol["offset"], 0)
        if not 0 <= segment <= 0xFFFF or not 0 <= offset <= 0xFFFF:
            raise ValueError(f"symbol {name!r} has an out-of-range segment or offset")

        address = segment * 16 + offset
        previous_address = seen_names.get(name)
        if previous_address is not None and previous_address != address:
            raise ValueError(
                f"symbol name {name!r} occurs at both "
                f"0x{previous_address:X} and 0x{address:X}"
            )
        seen_names[name] = address
        grouped[address].append(symbol)

    lines = [
        "// Generated by tools/generate_ida_idc.py; do not edit by hand.",
        "// Import into IDA after loading the executable with image base 0.",
        "// The address is the load-image linear address: segment * 16 + offset.",
        "",
        "#include <idc.idc>",
        "",
        "static main()",
        "{",
    ]

    for address, entries in sorted(grouped.items()):
        # IDA can store only one primary name per address. Prefer a procedure
        # record when aliases share an address, and retain the other names here.
        entries.sort(key=lambda item: int(item["debug_type"], 0) != 0x0201)
        primary = entries[0]["name"]
        aliases = [entry["name"] for entry in entries[1:]]
        if aliases:
            lines.append(
                f"    // Same-address aliases: {', '.join(aliases)}"
            )
        failure_message = f"Failed to import {primary} at 0x{address:X}\n"
        lines.extend(
            [
                f"    if (MakeNameEx(0x{address:X}, {idc_string(primary)}, SN_PUBLIC) == 0)",
                f"        Message({idc_string(failure_message)});",
            ]
        )

    lines.extend(["}", ""])
    return "\n".join(lines)


def main() -> None:
    script_dir = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "symbols",
        nargs="?",
        type=Path,
        default=script_dir / "reverse" / "publics.csv",
        help="CSV created by extract_zortech_symbols.py",
    )
    parser.add_argument(
        "output",
        nargs="?",
        type=Path,
        default=script_dir / "reverse" / "import_publics.idc",
        help="IDC output path",
    )
    args = parser.parse_args()

    with args.symbols.open(newline="", encoding="utf-8") as stream:
        reader = csv.DictReader(stream)
        required = {"name", "segment", "offset", "debug_type"}
        missing = required - set(reader.fieldnames or ())
        if missing:
            raise SystemExit(f"symbol CSV is missing columns: {', '.join(sorted(missing))}")
        symbols = list(reader)

    try:
        idc = generate_idc(symbols)
    except (KeyError, ValueError) as error:
        raise SystemExit(f"cannot generate IDC: {error}") from error

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(idc, encoding="ascii")
    print(f"wrote IDC for {len(symbols)} symbols to {args.output}")


if __name__ == "__main__":
    main()
